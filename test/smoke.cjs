const assert = require('node:assert/strict');
const { io } = require('socket.io-client');
const clients = [0,1,2].map(() => io('http://localhost:3000', { reconnection:false }));
const call = (s,event,...args) => new Promise((resolve,reject)=>s.timeout(3000).emit(event,...args,(err,res)=>err?reject(err):resolve(res)));
(async () => {
  await Promise.all(clients.map(s=>new Promise(r=>s.on('connect',r))));
  const host=await call(clients[0],'room:create',{name:'Host',avatar:'🤖',rounds:1,duration:30}); assert.equal(host.ok,true);
  const two=await call(clients[1],'room:join',{code:host.code,name:'Second',avatar:'🦊'}); assert.equal(two.ok,true);
  const three=await call(clients[2],'room:join',{code:host.code,name:'Third',avatar:'🐸'}); assert.equal(three.ok,true);
  assert.equal((await call(clients[1],'room:start')).ok,false);
  const choicePromises=clients.map(s=>new Promise(resolve=>s.once('word:choices',resolve)));
  assert.equal((await call(clients[0],'room:start')).ok,true);
  const sync=await call(clients[0],'room:sync'); assert.equal(sync.state.phase,'selecting'); assert.equal(sync.state.players.length,3); assert.equal(sync.state.word,undefined);
  const drawerIndex=[host,two,three].findIndex(x=>x.playerId===sync.state.drawerId);
  const choices=await choicePromises[drawerIndex];
  assert.equal(choices.length,3);
  assert.equal((await call(clients[drawerIndex],'word:select',choices[0])).ok,true);
  const other=(drawerIndex+1)%3;
  assert.equal((await call(clients[other],'canvas:op',{type:'clear'})).ok,false);
  assert.equal((await call(clients[drawerIndex],'canvas:op',{type:'stroke',points:[[0.1,0.2],[0.2,0.3]],color:'#171d30',size:6})).ok,true);
  const state=await call(clients[other],'room:sync'); assert.equal(state.state.ops.length,1); assert.equal(state.state.word,undefined);
  assert.equal((await call(clients[other],'chat:send',choices[0])).ok,true);
  const scored=await call(clients[other],'room:sync'); assert.equal(scored.state.players.find(x=>x.id===[host,two,three][other].playerId).score>0,true);
  const abandoned=io('http://localhost:3000',{reconnection:false});clients.push(abandoned);await new Promise(r=>abandoned.once('connect',r));
  const oldHost=await call(abandoned,'room:create',{name:'OldHost',rounds:1,duration:30});assert.equal(oldHost.ok,true);abandoned.disconnect();
  const newHost=io('http://localhost:3000',{reconnection:false});clients.push(newHost);await new Promise(r=>newHost.once('connect',r));
  const recovered=await call(newHost,'room:join',{code:oldHost.code,name:'NewHost'});assert.equal(recovered.ok,true);assert.equal(recovered.state.hostId,recovered.playerId);
  const guest=io('http://localhost:3000',{reconnection:false});clients.push(guest);await new Promise(r=>guest.once('connect',r));assert.equal((await call(guest,'room:join',{code:oldHost.code,name:'Guest'})).ok,true);assert.equal((await call(newHost,'room:start')).ok,true);
  console.log('Three-player socket smoke passed');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>clients.forEach(s=>s.disconnect()));
